// Single source: design/tokens.json → web CSS vars + Tailwind v4 theme, and field (React Native) TS theme.
// Run from repo root: node design/build-tokens.mjs
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const t = JSON.parse(readFileSync(join(root, "design/tokens.json"), "utf8"));

const colors = {};
(function walk(obj, prefix) {
  for (const [k, v] of Object.entries(obj)) {
    if (k.startsWith("_")) continue;
    const key = prefix ? `${prefix}-${k}` : k;
    if (typeof v === "string") colors[key.replaceAll("_", "-")] = v;
    else walk(v, key);
  }
})(t.color, "");

const px = (n) => `${n}px`;
const banner = "generated by design/build-tokens.mjs from design/tokens.json — do not edit";

// web/src/styles/tokens.css
let css = `/* ${banner} */\n:root {\n`;
for (const [k, v] of Object.entries(colors)) css += `  --color-${k}: ${v};\n`;
css += `  --font-sans: var(--font-figtree), ${t.font.sans};\n  --font-mono: ${t.font.mono};\n`;
for (const [k, v] of Object.entries(t.type)) css += `  --text-${k}: ${px(v.size)};\n  --text-${k}--line-height: ${px(v.line)};\n`;
for (const [k, v] of Object.entries(t.radius)) css += `  --radius-${k}: ${px(v)};\n`;
for (const [k, v] of Object.entries(t.shadow)) css += `  --shadow-${k}: ${v};\n`;
css += `  --motion-fast: ${t.motion.fast};\n  --motion-base: ${t.motion.base};\n  --ease-brand: ${t.motion.ease};\n`;
for (const [k, v] of Object.entries(t.layout)) if (typeof v === "number") css += `  --layout-${k}: ${px(v)};\n`;
css += "}\n";

// web/src/styles/tailwind-theme.css (Tailwind v4)
let tw = `/* ${banner} */\n@theme inline {\n`;
for (const k of Object.keys(colors)) tw += `  --color-${k}: var(--color-${k});\n`;
tw += "  --font-sans: var(--font-sans);\n  --font-mono: var(--font-mono);\n";
for (const k of Object.keys(t.type)) tw += `  --text-${k}: var(--text-${k});\n  --text-${k}--line-height: var(--text-${k}--line-height);\n`;
for (const k of Object.keys(t.radius)) tw += `  --radius-${k}: var(--radius-${k});\n`;
for (const k of Object.keys(t.shadow)) tw += `  --shadow-${k}: var(--shadow-${k});\n`;
tw += "  --spacing-sidebar: var(--layout-sidebar);\n  --spacing-header: var(--layout-header);\n  --spacing-touch: var(--layout-touch-min);\n";
tw += "  --container-content: var(--layout-content-max);\n}\n";

mkdirSync(join(root, "web/src/styles"), { recursive: true });
writeFileSync(join(root, "web/src/styles/tokens.css"), css);
writeFileSync(join(root, "web/src/styles/tailwind-theme.css"), tw);

// field/src/theme/tokens.ts
const rn = {
  color: colors,
  font: { sans: "Figtree", mono: "monospace" },
  type: t.type,
  space: t.space,
  radius: t.radius,
  layout: t.layout,
};
mkdirSync(join(root, "field/src/theme"), { recursive: true });
writeFileSync(
  join(root, "field/src/theme/tokens.ts"),
  `// ${banner}\nexport const tokens = ${JSON.stringify(rn, null, 2)} as const;\nexport type ColorToken = keyof typeof tokens.color;\n`,
);

console.log(`tokens: ${Object.keys(colors).length} colours → web/src/styles, field/src/theme`);
